/** Text für die Pixelschrift aufbereiten: Großbuchstaben, ß → SS, unbekannte Zeichen entfernen. */
export function normalizeText(text: string): string {
  return text.toUpperCase().replace(/ß/g, 'SS')
    .split('').filter(c => c === ' ' || GLYPHS[c]).join('')
    .replace(/\s+/g, ' ').trim();
}

/** Breite einer Zeile in Schrift-Pixeln (1 Pixel Abstand zwischen Zeichen, Leerzeichen 3 Pixel breit). */
export function lineWidth(line: string): number {
  let wdt = 0;
  for (const c of line) wdt += c === ' ' ? 3 : GLYPH_W + 1;
  return Math.max(0, wdt - 1);
}

/** Ist das Pixel (gx, gy) des Zeichens gesetzt? */
export function glyphPixel(c: string, gx: number, gy: number): boolean {
  return GLYPHS[c]?.[gy]?.[gx] === '#';
}
